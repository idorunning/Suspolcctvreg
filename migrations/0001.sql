CREATE TABLE IF NOT EXISTS cameras (id TEXT PRIMARY KEY, data TEXT NOT NULL, revision INTEGER NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS photos (camera_id TEXT PRIMARY KEY REFERENCES cameras(id) ON DELETE CASCADE, jpeg BLOB NOT NULL);
CREATE TABLE IF NOT EXISTS sessions (token_hash TEXT PRIMARY KEY, csrf TEXT NOT NULL, expires INTEGER NOT NULL, last_seen INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS login_limits (key TEXT PRIMARY KEY, attempts INTEGER NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS audit (id INTEGER PRIMARY KEY AUTOINCREMENT, action TEXT NOT NULL, camera_id TEXT, at INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS audit_at ON audit(at);
